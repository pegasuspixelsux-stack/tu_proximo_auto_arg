let dealerRowCount = 0;

const EXTRA_VEHICLES: Vehicle[] = EXTRA_ROWS.map(
  (
    [
      make,
      model,
      year,
      price,
      km,
      transmission,
      fuelType,
      bodyType,
      sellerType,
      imageId,
    ],
    i,
  ) => {
    const base =
      BASE_VEHICLES.find((v) => v.id === imageId) ?? BASE_VEHICLES[0];
    const dealership =
      sellerType === "dealer"
        ? DEALERSHIPS[dealerRowCount++ % DEALERSHIPS.length]
        : undefined;
    const created = new Date(Date.UTC(2026, 9, 10 - i));
    return {
      id: String(BASE_VEHICLES.length + i + 1),
      make,
      model,
      year,
      price,
      mileage: Math.round(km / 1.60934),
      transmission,
      fuelType,
      bodyType,
      image: imageId.startsWith("photo-") ? img(imageId) : base.image,
      location:
        dealership?.location ?? PRIVATE_LOCATIONS[i % PRIVATE_LOCATIONS.length],
      sellerType,
      dealership,
      sellerPhone:
        sellerType === "private" ? `598991${String(20000 + i)}` : undefined,
      createdAt: created.toISOString().slice(0, 10),
    };
  },
);

export const HOMEPAGE_LIMIT = 12;

export const SAMPLE_VEHICLES: Vehicle[] = [
  ...BASE_VEHICLES,
  ...EXTRA_VEHICLES,
].map((v, i) => ({ ...v, homepage: v.homepage ?? i < HOMEPAGE_LIMIT }));

export const HOMEPAGE_VEHICLES: Vehicle[] = SAMPLE_VEHICLES.filter(
  (v) => v.homepage,
).slice(0, HOMEPAGE_LIMIT);

export const vehiclesByDealer = (dealershipId: string) =>
  SAMPLE_VEHICLES.filter((v) => v.dealership?.id === dealershipId);

export const getVehicle = (id: string) =>
  SAMPLE_VEHICLES.find((v) => v.id === id);
